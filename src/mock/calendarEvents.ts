import type { CalendarEvent, CalendarEventType } from '../types'

export const CALENDAR_SPORTS = [
  'All',
  'Football',
  'Baseball',
  'Softball',
  'Soccer',
  'Basketball',
  'Volleyball',
  'Lacrosse',
  'Track & Field',
] as const

export type CalendarSport = (typeof CALENDAR_SPORTS)[number]

const CAMP_WORDS = /camp|junior day|combine|showcase|7-on-7/i

export function isCampEvent(item: CalendarEvent): boolean {
  return CAMP_WORDS.test(item.title) || CAMP_WORDS.test(item.notes)
}

const PERIOD_TYPES: CalendarEventType[] = [
  'Dead Period',
  'Quiet Period',
  'Contact Period',
  'Evaluation Period',
  'Recruiting Shutdown',
]

export function currentRecruitingPeriod(sport: string, date: string): CalendarEvent | undefined {
  return mockCalendarEvents.find(
    (item) =>
      PERIOD_TYPES.includes(item.type) &&
      item.sport === sport &&
      item.startDate <= date &&
      item.endDate >= date,
  )
}

export const CALENDAR_SOURCE =
  'NCAA Division I 2026–27 recruiting calendars (updated July 30–August 4, 2026), NCAA signing-date formula, College Board SAT weekend dates, and ACT national dates. Football January 2027 follows the FBS Oversight Committee action of July 23, 2026; the 2026–27 FBS PDF was not posted at the time these dates were loaded.'

function event(
  id: string,
  title: string,
  type: CalendarEventType,
  sport: string,
  startDate: string,
  endDate: string,
  notes: string,
): CalendarEvent {
  return { id, title, type, sport, startDate, endDate, notes }
}

